import type { StarterFeaturePlan } from "./featurePlan.ts";

function renderGitignore(): string {
  return `node_modules
.env
.env.local
dist
frontend/dist
storage/*.sqlite
storage/*.sqlite-journal
storage/*.sqlite-wal
storage/*.sqlite-shm
coverage
*.tsbuildinfo
`;
}

function renderPackageJson(
  projectName: string,
  options: { workspaceDependencies?: boolean; plan?: StarterFeaturePlan } = {},
): string {
  const coreDeps: Record<string, string> = options.workspaceDependencies
    ? {
        "@getstrata/bootstrap": "workspace:*",
        "@getstrata/cli": "workspace:*",
        "@getstrata/core": "workspace:*",
      }
    : {
        "@getstrata/bootstrap": "^3.0.5",
        "@getstrata/cli": "^3.0.5",
        "@getstrata/core": "^3.0.5",
      };
  coreDeps.eta = "^4.6.0";
  if (options.plan?.decisions.mysqlDependency) {
    coreDeps.mysql2 = "^3.24.3";
  }

  const scripts: Record<string, string> = {
    dev: "strata dev",
    start: "strata start",
    "db:migrate": "strata migrate",
    "db:seed:demo": "bun run src/db/seed.ts",
    "db:fresh": "strata migrate:fresh",
    "queue:work": "strata queue:work",
    "outbox:work": "strata outbox:work",
    check: "tsc --noEmit",
  };
  if (options.plan?.decisions.frontendBuild) {
    scripts["frontend:install"] = "cd frontend && bun install";
    scripts["frontend:build"] = "cd frontend && bun run build";
    scripts["frontend:dev"] = "cd frontend && bun run dev";
  }

  return `${JSON.stringify(
    {
      name: projectName,
      version: "0.1.0",
      private: true,
      type: "module",
      scripts,
      engines: { bun: ">=1.4.4" },
      overrides: { "bun-types": ">=1.4.4" },
      dependencies: coreDeps,
      devDependencies: {
        "@types/bun": ">=1.4.4",
        typescript: "^7.0.2",
      },
    },
    null,
    2,
  )}\n`;
}

function renderLayersManifest(projectName: string, plan: StarterFeaturePlan): string {
  const layers = plan.layers;
  return `${JSON.stringify(
    {
      name: projectName,
      generatedBy: "create-strata",
      layers: {
        frontend: layers.frontend,
        database: layers.database,
        auth: layers.auth,
        tenancy: layers.tenancy,
        cache: layers.cache,
        queue: layers.queue,
        mail: layers.mail,
        spaPrefix: layers.spaPrefix,
        extras: layers.extras,
        docker: layers.docker,
      },
      notes:
        "Generated by create-strata. Change layers later with flags or by editing env and bootstrap files.",
    },
    null,
    2,
  )}\n`;
}

export { renderGitignore, renderLayersManifest, renderPackageJson };
